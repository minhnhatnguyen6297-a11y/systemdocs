#!/usr/bin/env node
// Sinh docs/screen-map.yaml từ app đang chạy qua CDP (harness /workspace/usability).
// Dùng: tools/screen-map/gen-screen-map.sh  (tự launch + stop app)  hoặc
//       CDP_PORT=9555 node tools/screen-map/gen-screen-map.cjs > docs/screen-map.yaml
// Chỉ ĐỌC + click điều hướng (rail, tab, "+ Hồ sơ mới"); profile tạm, không dữ liệu thật.
// Phần do người viết (test liên quan, gotchas) nằm ở tools/screen-map/overrides.json và được gộp vào.
const fs = require('fs'); const path = require('path');
const UX = process.env.UX_DIR || '/workspace/usability';
const { connect, snapshot, actions } = require(path.join(UX, 'ux-lib.cjs'));
const overrides = JSON.parse(fs.readFileSync(path.join(__dirname, 'overrides.json'), 'utf8'));
const q = (s) => JSON.stringify(String(s));
const parseLine = (l) => { const m = l.trim().match(/^([a-z]+)(?: "(.*?)")?(.*)$/); return m && { role: m[1], name: m[2] || '', extra: m[3].trim() }; };
const INTERESTING = new Set(['button', 'tab', 'textbox', 'combobox', 'checkbox', 'radio', 'searchbox', 'heading', 'dialog', 'link', 'switch', 'spinbutton']);

async function capture(page, scope) {
  await page.waitForTimeout(700);
  const snap = await snapshot(page, scope);
  const els = []; const seen = new Set();
  for (const l of snap.split('\n')) { const p = parseLine(l); if (!p || !INTERESTING.has(p.role) || !p.name) continue;
    const sel = `${p.role}:${p.name}`; if (seen.has(sel)) continue; seen.add(sel); els.push(sel); }
  const status = (snap.match(/^\s*status: "(.*)"$/m) || [])[1];
  return { els, status, modal: snap.startsWith('!!') };
}

(async () => {
  const { browser, page } = await connect();
  const screens = []; let rail = [];
  try {
    const top = await capture(page);
    rail = top.els.filter((s) => s.startsWith('button:')).slice(0, 5); // icon rail = 5 nút đầu
    for (const r of rail) {
      await page.keyboard.press('Escape').catch(() => {}); await actions.click(page, r);
      const c = await capture(page);
      const tabs = c.els.filter((s) => s.startsWith('tab:'));
      screens.push({ id: r.slice(7), reach: [`click ${r}`], ...c });
      for (const t of tabs) {
        await actions.click(page, t);
        const ct = await capture(page);
        screens.push({ id: `${r.slice(7)}/${t.slice(4)}`, reach: [`click ${r}`, `click ${t}`], ...ct });
      }
    }
    // Màn soạn hồ sơ có dữ liệu: cần tạo hồ sơ mới (profile tạm, rỗng).
    for (const flow of overrides.flows || []) {
      try { for (const st of flow.steps) { const [cmd, ...a] = st; await actions[cmd](page, ...a); }
        screens.push({ id: flow.id, reach: flow.steps.map((s) => s.join(' ')), ...(await capture(page)) });
      } catch (e) { screens.push({ id: flow.id, reach: flow.steps.map((s) => s.join(' ')), error: e.message.split('\n')[0], els: [] }); }
    }
  } finally { await browser.close().catch(() => {}); }

  const out = [];
  out.push('# GENERATED by tools/screen-map/gen-screen-map.cjs — đừng sửa tay phần "screens";');
  out.push('# sửa tools/screen-map/overrides.json rồi chạy lại tools/screen-map/gen-screen-map.sh.');
  out.push('# Selector theo cú pháp harness ux.cjs: "role:Tên hiển thị" (không dùng class CSS/vị trí DOM).');
  out.push('version: 1');
  out.push(`generated_at: ${q(new Date().toISOString())}`);
  out.push(`launch: ${q(overrides.launch)}`);
  out.push('global_selectors:  # icon rail, có trên mọi màn');
  for (const r of rail) out.push(`  - ${q(r)}`);
  out.push('screens:');
  for (const s of screens) {
    const o = (overrides.screens || {})[s.id] || {};
    s.els = s.els.filter((e) => !rail.includes(e));
    out.push(`  - id: ${q(s.id)}`);
    if (o.purpose) out.push(`    purpose: ${q(o.purpose)}`);
    out.push('    reach_from_launch:'); for (const r of s.reach) out.push(`      - ${q(r)}`);
    if (s.status) out.push(`    status_at_capture: ${q(s.status)}`);
    if (s.modal) out.push('    modal_open_at_capture: true');
    if (s.error) out.push(`    capture_error: ${q(s.error)}`);
    out.push('    key_selectors:'); if (!s.els.length) out[out.length - 1] += ' []';
    for (const e of s.els.slice(0, 25)) out.push(`      - ${q(e)}`);
    if (s.els.length > 25) out.push(`      # … +${s.els.length - 25} phần tử khác (xem ux.cjs snapshot)`);
    out.push('    related_tests:'); const t = o.tests || []; if (!t.length) out[out.length - 1] += ' []';
    for (const x of t) out.push(`      - ${q(x)}`);
    if (o.gotchas) { out.push('    gotchas:'); for (const g of o.gotchas) out.push(`      - ${q(g)}`); }
  }
  process.stdout.write(out.join('\n') + '\n');
})().catch((e) => { console.error(e); process.exit(1); });
